package org.todo.spring_todo.todo;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.todo.spring_todo.todo.dto.CreateTodoRequest;

import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/**
 * SESSION 3 — TodoRepository is now an interface generated by Spring Data,
 * so the test uses a Mockito mock instead of the real thing.
 */
class TodoServiceTest {

    private final Instant fixedNow = Instant.parse("2026-01-01T09:00:00Z");
    private final List<String> notifications = new ArrayList<>();

    private TodoRepository todoRepository;
    private TodoService todoService;

    @BeforeEach
    void setUp() {
        todoRepository = mock(TodoRepository.class);
        todoService = new TodoService(todoRepository,
                (username, message) -> notifications.add(message),
                Clock.fixed(fixedNow, ZoneOffset.UTC));
    }

    @Test
    void createSetsTimestampAndDefaultPriority() {
        when(todoRepository.save(any(Todo.class))).thenAnswer(call -> call.getArgument(0));

        Todo created = todoService.create(new CreateTodoRequest("Buy milk", null, null));

        assertThat(created.getCreatedAt()).isEqualTo(fixedNow);
        assertThat(created.getPriority()).isEqualTo(Priority.MEDIUM);
        assertThat(notifications).containsExactly("Created todo: Buy milk");
    }

    @Test
    void findByIdThrowsForUnknownId() {
        when(todoRepository.findById(99L)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> todoService.findById(99L))
                .isInstanceOf(TodoNotFoundException.class)
                .hasMessage("Todo 99 was not found");
    }

    @Test
    void toggleUsesDirtyCheckingNotSave() {
        Todo todo = new Todo("Read docs", null, Priority.LOW, fixedNow);
        when(todoRepository.findById(7L)).thenReturn(Optional.of(todo));

        todoService.toggle(7L);

        assertThat(todo.isCompleted()).isTrue();
        verify(todoRepository, never()).save(any());
    }
}
